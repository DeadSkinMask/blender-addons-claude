"""Geometry Nodes instances: MultiMesh (mesh GLB + chunked .gmmi transforms) or realized nodes.

.gmmi = magic "GMMI0001", uint32 count, then per instance 12 little-endian float32
(Godot basis columns x, y, z, then origin) — the same format as the Godot MultiMesh
Scatter addon. Instances are split in chunks along X (the side-scrolling axis) so
Godot can cull the chunks outside the camera.

Blender reports two kinds of instances: object instances (Collection Info, or
Object Info "As Instance") point to the source object; geometry instances point
to the host itself with a temporary mesh. Both are grouped by the instanced
data, and a mesh copy is taken during the iteration (instance data is only
valid then).
"""

import math
import os
import struct

import bpy
from mathutils import Matrix

from . import coords, manifest, static_export

MAGIC = b"GMMI0001"
SUBDIR = "multimesh"


class Group:
    """Instances of one geometry generated by one host."""

    __slots__ = ("name", "type", "matrices", "mesh")

    def __init__(self, name, type_):
        self.name, self.type, self.matrices, self.mesh = name, type_, [], None


def policy(obj, scene):
    value = obj.gbridge.instances
    return scene.gbridge.instances if value == 'SCENE' else value


def collect(depsgraph, hosts, with_meshes=False):
    """{host: [Group]} for the instances generated by each host.

    With `with_meshes`, each geometry group gets a temporary mesh copy
    (group.mesh) that the caller must free with free_meshes().
    """
    wanted = set(hosts)
    by_host = {}
    for inst in depsgraph.object_instances:
        if not inst.is_instance or inst.parent is None:
            continue
        host = inst.parent.original
        if host not in wanted:
            continue
        obj = inst.object
        source = obj.original
        is_object_instance = source is not None and source != host
        data = obj.data
        key = ("object", source.name) if is_object_instance else ("data", data.as_pointer() if data else 0)
        groups = by_host.setdefault(host, {})
        group = groups.get(key)
        if group is None:
            if is_object_instance:
                name = source.name
            else:
                name = data.name if data is not None else "instancia"
            group = groups[key] = Group(bpy.path.clean_name(name), obj.type)
            if with_meshes and obj.type == 'MESH' and data is not None:
                # The temporary object's data is the instanced geometry; new_from_object
                # would re-evaluate the host instead (an empty mesh for a pure scatter).
                group.mesh = data.copy()
            elif with_meshes and obj.type in static_export.GEOMETRY_TYPES:
                group.mesh = bpy.data.meshes.new_from_object(obj, preserve_all_data_layers=True, depsgraph=depsgraph)
        group.matrices.append(inst.matrix_world.copy())
    return {host: list(groups.values()) for host, groups in by_host.items()}


def free_meshes(found):
    for groups in found.values():
        for group in groups:
            if group.mesh is not None:
                bpy.data.meshes.remove(group.mesh)
                group.mesh = None


def gmmi_bytes(matrices):
    data = bytearray(MAGIC)
    data += struct.pack("<I", len(matrices))
    for m in matrices:
        data += struct.pack("<12f", *coords.matrix(m))
    return bytes(data)


def chunks(matrices, size):
    """{chunk index: [matrix]} by the X of each instance (same axis in Blender and Godot)."""
    result = {}
    for m in matrices:
        index = math.floor(m.translation.x / size) if size > 0 else 0
        result.setdefault(index, []).append(m)
    return dict(sorted(result.items()))


def _color_mode(host, scene):
    value = host.gbridge.vertex_colors
    return scene.gbridge.vertex_colors if value == 'SCENE' else value


def realized(found, scene):
    """Extra nodes (name, mesh, matrix, color mode) for static_export."""
    nodes = []
    for host, groups in found.items():
        for group in groups:
            if group.mesh is None:
                continue
            for i, m in enumerate(group.matrices):
                nodes.append(("{}_{}_{}".format(host.name, group.name, i), group.mesh, m, _color_mode(host, scene)))
    return nodes


def export_multimesh(context, found, output_dir, level, written_files):
    """Write mesh GLBs and .gmmi chunks; return the manifest entities.

    `written_files` collects every file produced (to clean stale ones afterwards).
    """
    folder = os.path.join(output_dir, SUBDIR)
    scene = context.scene
    chunk_size = scene.gbridge.multimesh_chunk
    entities = []
    for host, groups in found.items():
        for group in groups:
            if group.mesh is None:
                continue
            name = bpy.path.clean_name("{}_{}".format(host.name, group.name))
            mesh_path = os.path.join(folder, "{}_{}.glb".format(level, name))
            extra = [(group.name, group.mesh, Matrix.Identity(4), _color_mode(host, scene))]
            if static_export.export(context, [], mesh_path, level, extra=extra) is None:
                continue
            written_files.add(mesh_path)
            entity_chunks = []
            for index, chunk in chunks(group.matrices, chunk_size).items():
                path = os.path.join(folder, "{}_{}_{}.gmmi".format(level, name, index))
                manifest.write_bytes_if_changed(path, gmmi_bytes(chunk))
                written_files.add(path)
                entity_chunks.append({"transforms": SUBDIR + "/" + os.path.basename(path), "count": len(chunk)})
            entities.append({
                "uid": "{}:{}".format(host.gbridge.uid, group.name),
                "type": "multimesh",
                "name": name,
                "mesh": SUBDIR + "/" + os.path.basename(mesh_path),
                "chunks": entity_chunks,
            })
    return entities


def remove_stale(output_dir, level, written_files):
    """Delete this level's MultiMesh files that the current export did not produce."""
    folder = os.path.join(output_dir, SUBDIR)
    if not os.path.isdir(folder):
        return
    for name in os.listdir(folder):
        path = os.path.join(folder, name)
        if not name.startswith(level + "_"):
            continue
        base = path[:-len(".import")] if name.endswith(".import") else path
        if base.endswith((".glb", ".gmmi")) and base not in written_files:
            os.remove(path)
